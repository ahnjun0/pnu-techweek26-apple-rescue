# 가짜 월드 5종에서 "진짜 벽까지의 거리" 를 직접 재서 정했다:
#   0.03 → 최악 여유 20.0 cm, 154초, 35cm 미만 2.1%
#   0.12 → 최악 여유 24.4 cm, 138초, 1.3%

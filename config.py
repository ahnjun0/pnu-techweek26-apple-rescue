# ⚠️ 0.20 -> 0.15. 근거: PROTO 에서 확인한 **실제 몸체** 는 LiDAR 기준 0.086 m
#    까지만 뻗는데(TurtleBot3Burger.proto:186-201, 43-46), 0.20 이면 0.33 m 를
#    요구해 **몸 크기의 3.8배** 다. 0.15 면 0.28 m = 3.3배.
#    실측: 좁은 곳을 지날 때마다 기어간다 — maze2 는 시간의 46.6%, comb1 은

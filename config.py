# --- DWA (Dynamic Window Approach) — 대안 주행기 ---------------------------
# 지금 방식은 "경로를 따라가되 위험하면 멈춘다" 라 정지·대기·탈출 상태가 필요하다.
# DWA 는 (전진속도, 회전속도) 후보를 뿌려 각각 몇 초 앞을 모의주행해 보고
# 점수가 제일 좋은 것을 고른다. 애초에 위험한 명령을 내지 않으므로 상태가 필요 없다.
FOLLOW_USE_DWA = True          # True 면 DWA 로 주행한다

# ⚠️ 이 값이 너무 짧으면 "사람을 예측해도 소용없다".
#    1.2 초 × 로봇 속도 0.15 m/s = 18 cm 앞만 보는 셈인데,
#    그 사이 사람은 48 cm 를 간다 — 만날 지점까지 가 보지도 못한다.
DWA_SIM_TIME = 1.2              # [s] 후보 하나를 몇 초 앞까지 모의주행할 것인가
DWA_SIM_STEPS = 8               # 그 구간을 몇 점으로 나눌 것인가
DWA_SPEED_SAMPLES = 7           # 전진속도 후보 개수
DWA_TURN_SAMPLES = 17           # 회전속도 후보 개수
DWA_MAX_ACCEL = 0.6             # [m/s^2] 한 틱에 바꿀 수 있는 전진속도 (부드러움의 핵심)
DWA_MAX_ANG_ACCEL = 4.0         # [rad/s^2] 한 틱에 바꿀 수 있는 회전속도
# ⚠️ "목표를 옮기는 고정비(감속·회전·재계획·재가속)" 를 비용에 더해 봤다가 **뺐다.**
#    가설: "1 m 당 이득" 점수가 발밑의 부스러기를 늘 이기게 만든다
#        발밑 0.2 m / 이득  20칸 -> 0.010   ← 이긴다
#        서쪽 3.5 m / 이득 267칸 -> 0.013
#    고정비 0.395 m 를 더하면 큰 목표가 이긴다 (0.0146 vs 0.0298). 계산은 맞았다.
#    그런데 **측정이 아니라고 했다**: comb1 은 그대로 1/3 / 탐색률 51% 였고,
#    comb0 만 40.6 -> 46.0 m 로 나빠졌다 (maze0 은 동일).
#    즉 comb1 의 목표 왕복은 부스러기 때문이 아니다. 원인은 아직 모른다.

DWA_REVERSE_SPEED = 0.06        # [m/s] 후보에 넣을 후진 속도 (0 이면 후진 안 함)
DWA_IDLE_SPEED = 0.01           # [m/s] 이 이하는 "전진이 아니다" 로 본다

# ⚠️ 후보를 고르는 창의 폭은 **제어 주기** 가 아니라 **결정 지평** 이어야 한다.
#    한 틱(16 ms)의 가속 권한이면 창 폭이 0.6 × 0.016 = 0.0096 m/s 뿐이라,
#    후진 중에는 전진 후보가 창에 아예 없다 — 후진 벌점이 걸릴 자리가 없어서
#    후진이 "이겨서" 가 아니라 "유일해서" 뽑힌다.
#    실측 (comb0, 51420 틱): 후진 명령 70.5%, 그중 100% 가 "창에 전진 없음".
#    조준점이 **앞** 인데도 후진한 틱이 45.4%, 더 깊이 파고든 틱(30.3%)이
#    회복 중인 틱(6.1%)의 5배였다. 평균 명령속도가 +0.017 m/s 였다.
#    (컨트롤러 주기를 물리 스텝에서 떼어낼 때 이 창을 같이 떼지 않은 누락이다.)
#    최소 요구: 가장 깊은 후진에서도 창이 전진 후보(> DWA_IDLE_SPEED)에 닿아야
#    한다 → 폭 > DWA_REVERSE_SPEED + DWA_IDLE_SPEED. 여유로 2배를 준다.
DWA_ACCEL_HORIZON = ((DWA_REVERSE_SPEED + 2.0 * DWA_IDLE_SPEED)
                     / DWA_MAX_ACCEL)   # [s] = 0.133
DWA_RAY_STRIDE = 3              # 장애물 점을 몇 개마다 하나씩 쓸지 (성능)

# 점수 가중치 — 셋의 상대 크기만 의미가 있다
DWA_WEIGHT_GOAL = 1.0           # 경로 위 목표점에 가까워지는가
DWA_WEIGHT_CLEARANCE = 0.8      # 장애물에서 멀리 떨어지는가
DWA_CLEARANCE_CAP = 0.8         # [m] 이보다 여유가 크면 더 쳐주지 않는다
# 후진은 "끼였을 때 빠져나오는 수단" 이지 이동 수단이 아니다.
# ⚠️ 이 벌점이 없으면, 목표가 뒤에 있을 때 돌아서지 않고 그냥 뒤로 기어간다.
#    후진 상한이 낮아서 100초에 1.6 m 밖에 못 갔다 (복귀가 시간 초과로 실패).
DWA_REVERSE_PENALTY = None      # 아래에서 DWA_IDLE_PENALTY 와의 관계로 정한다

# --- 가만히 있는 후보에 매기는 벌점 -------------------------------------------
# ⚠️ 속도 0 후보는 궤적이 "점" 이라 **장애물 여유 점수가 늘 만점** 이다. 목표가
#    멀면 후보들 간 목표 점수 차이가 작아져, 여유 점수가 승부를 갈라 "가만히
#    있기" 가 이긴다. 계측: 사람 없는 지도에서 출력이 (0,0) 인 틱이 전체의 39.6%
#    (356.7초) 였고, 그중 임무 쪽 분기에서 나온 것은 **4틱** 뿐이었다 —
#    전부 DWA 가 스스로 고른 것이었다.
#
# ⚠️ 예전에 "속도 0 후보를 아예 빼기" 를 시험하고 되돌린 기록이 있는데, 그 측정은
#    **보행자가 있는 월드** 에서 한 것이다 (닿은시간 12.8 -> 23.0초로 나빠졌다).
#    사람 근처에서는 가만히 있는 것이 옳다 — 내가 다가가지는 않으니까.
#    그래서 없애지 않고 **벌점** 으로 두고, 사람이 보일 때는 벌점을 끈다
#    (follower.step 의 allow_idle). 조건이 다르면 답도 다르다.
# 값은 관계로 정한다. 점수는 두 항의 정규화 합이라 최대 (GOAL + CLEARANCE) 이므로,
# 벌점이 그보다 크면 **안전한 후보가 하나라도 있는 한** 가만히 있기는 절대 못 이긴다.
# 그리고 안전한 후보가 하나도 없으면 score[~safe] = -inf 라 가만히 있기가 살아남는다.
# 즉 "정말 갈 데가 없을 때만 선다" 는 뜻이 된다. 0 이면 끈다.
# ⚠️ 0.5 로 두었더니 여유 가중치(0.8)를 못 이겨 여전히 28% 가 정지였다.
DWA_IDLE_PENALTY = DWA_WEIGHT_GOAL + DWA_WEIGHT_CLEARANCE + 0.1

# 우선순위를 **관계** 로 못박는다:  전진  >  제자리 회전  >  후진
# ⚠️ 후진 벌점이 정지 벌점보다 작았더니(1.2 < 1.9), 로봇이 가만히 있느니 뒤로
#    물러나는 쪽을 골랐다. LiDAR 가 한 틱 튀었을 때 후진해 버려 안전 시험이 깨졌다
#    (tests/test_mission.py::test_a_single_tick_lidar_spike_is_ignored).
#    뒤로 가는 것은 제자리에서 방향을 고르는 것보다 나쁜 선택이어야 한다.
DWA_REVERSE_PENALTY = DWA_IDLE_PENALTY + 0.1
# 직전에 돌던 방향을 유지하는 후보에 주는 가산점 (0 = 끔).
# ⚠️ debug/doorway_report.py: 버벅인 19구간 중 15구간은 전진 후보가 **100% 안전** 했는데도
#    회전 방향이 2초에 6~22번 뒤바뀌었다 — 여유가 아니라 방향 선택이 흔들린 것이다.
DWA_TURN_KEEP = 0.0

# DWA 가 후보를 "부딪힌다" 고 버리는 하한: 로봇 반경 + 이 값.
# ⚠️ 이건 SAFETY_CORRIDOR_CLEARANCE(추종+정지 주행기의 통로 반폭)와 다른 값이다.
#    한때 같은 상수를 둘이 나눠 썼는데, 그 값(0.03)은 통로 쪽 사정으로 정해진
#    것이라 DWA 에는 너무 낮았다. DWA 가 벽에서 0.16 m 까지를 "안전" 으로 쳐서,
